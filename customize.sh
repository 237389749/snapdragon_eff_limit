#    追求的是「最佳能效点」而非极限性能，玩游戏若觉得不够可自行调高。
#
#  CPU 频率档位参考 (kHz，实测自本机，不同机型可能略有差异)
#  脚本会自动对齐到「≤目标值」的最近合法档位，填任意值即可生效
