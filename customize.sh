#  💡 为什么这样设置（能效依据）：
#    内核 capacity（小米13 实测）：A510=280，A715/A710=855，X3=1024。
#    单核算力比大致 1 : 3.05 : 3.66，但功耗比远大于此——越往上每 MHz 越贵。
