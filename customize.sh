#    ① A510 小核（policy0，档位步长%在 1.67GHz 后掉到 ~6.5%）
#       步长从 1.4592→1.5552 的 +6.6%、1.6692→1.7842 的 +6.9% 开始收窄，
#       说明电压台阶已进入“频率涨得慢、电压涨得快”区。
#       → 锁 1.5552GHz：约 77% 性能，后台/待机最划算。
#
#    ② A715/A710 中核（policy3，档位步长%在 2.05GHz 后掉到 7% 以下）
#       2.0544→2.1888 +6.5%、2.1888→2.3232 +6.1%、2.3232→2.4576 +5.8%，
#       而 2.0544 之前每档还有 7%~8%。2.0~2.1GHz 是这代 A715 的甜点。
#       → 锁 2.0544GHz：日常主力，重载也不至于烫。
#
#    ③ X3 大核（policy7，档位步长%在 2.09GHz 后掉到 5%~6%）
#       2.0928→2.2272 +6.4%、2.2272→2.3424 +5.2%、2.5920→2.7264 +5.2%；
#       而 3.1872 的 boost 档相对 2.9568 是 +7.8% 的跳变，属于典型“高价档”。
#       → 锁 2.0928GHz：约为 X3 峰值的 66%，但拿到 2GHz 级别的单线程体验，
#         避开 2.4GHz 以上的功耗陡升区。
#
#    ④ GPU Adreno 740（680/615/550/475/401/348/295/220）
#       小米13 默认已被热控压在 550MHz（thermal_pwrlevel=2）。
