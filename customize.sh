#    cpu0-5  大核 Oryon      最高 3.53GHz   (policy0)
#    cpu6-7  超大核 Oryon    最高 4.32GHz   (policy6)
#
#  💡 为什么这样设置（能效依据）：
#    设备树能效参数：每 MHz 算力/功耗系数
#      大核(cpu0-5)  cap=1792 dpc=238  能效比 7.5   日常主力
#      超大核(cpu6-7) cap=1894 dpc=588  能效比 3.2   同频算力仅比大核高5.7%，
#                                        功耗系数却是2.5倍 → 能效黑洞，应拉低
#    → 大核锁 2.0GHz 左右（日常主力，避开高频电压暴涨区）
#    → 超大核锁 1.7GHz 左右（能效黑洞；且实测 memlat 表显示超大核跑 4.19GHz
