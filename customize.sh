#      443     LOW_SVS  (64)
#      389     LOW_SVS_D1(60)
#      342     MIN_SVS  (56)
#      222     最低档   (52)
#      160     最低档   (50)
#
#  ---------------- 8E 实际生效变量 ----------------
# 大核 cpu0-5 (policy0) 最大频率 (默认 1996800 ≈ 2.0GHz)
P0_FREQ=1996800

# 超大核 cpu6-7 (policy6) 最大频率 (默认 1689600 ≈ 1.69GHz，能效黑洞拉低)
