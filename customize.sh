# ---------- 处理器型号检测 ----------
CHIP_ID_FILE="/sys/devices/soc0/chip_id"
CHIP_ID=""
if [ -f "$CHIP_ID_FILE" ]; then
    CHIP_ID=$(cat "$CHIP_ID_FILE" 2>/dev/null | tr -d '\n\r')
fi
SOC=""
case "$CHIP_ID" in
    SM8650)
        SOC="g3"
        ui_print "✅ 检测到 SM8650 (骁龙8Gen3)，使用 8G3 逻辑 (4集群+5-6锁低频)"
        ;;
    SM8750)
        SOC="e8"
        ui_print "✅ 检测到 SM8750 (骁龙8Elite)，使用 8E 逻辑 (2集群+超大核拉低)"
        ;;
    *)
        ui_print "❌ 错误：无法识别芯片型号 '$CHIP_ID'"
        ui_print "   此模块仅支持 骁龙8Gen3 (SM8650) 或 骁龙8Elite (SM8750)"
        abort
        ;;
esac
ui_print ""

mkdir -p "$MODPATH/config"

# 创建统一 freq.conf（包含两个平台的完整信息，仅当前平台变量生效）
FREQ_FILE="$MODPATH/config/freq.conf"
if [ ! -f "$FREQ_FILE" ]; then
    cat > "$FREQ_FILE" << 'EOF'
# ============================================================
#  骁龙8Gen3 / 8Elite 能效限频配置（通用版）
#  以下完整保留两个平台的频率表 / 电压表 / 能效说明
#  只修改「你当前机型」分节里的变量即可，另一平台信息保留参考
#  修改后需要重启设备生效
# ============================================================

# ############################################################
# 【A】骁龙8Gen3 (SM8650) — 1+3+2+2 架构
# ############################################################
#
#  CPU 集群划分 (0-7)：
#    cpu0-1  小核 A520         最高 2.27GHz   (policy0)
#    cpu2-4  中核 A720 高频版   最高 3.15GHz   (policy2)
#    cpu5-6  中核 A720 低频版   最高 2.96GHz   (policy5)
#    cpu7    大核 X4           最高 3.30GHz   (policy7)
#
#  ⚠️ 架构要点（8G3 解析）：
#    5-6 与 7 共享电压域 —— 5-6 升频会让 7 被动跑在更高电压上，
#    因此 5-6 必须锁低频，防止其吃负载升频拉高 7 的电压；
#    7 跑高频时会带动 5-6 实际频率，无需给 5-6 单独升频。
#    模块只设 scaling_max_freq，不碰 min 频率与 governor。
#
#  💡 为什么这样设置（能效依据）：
#    设备树能效参数：每 MHz 算力/功耗系数
#      A520(0-1)  cap=1024 dpc=100  能效比 10.2  ★最高，适合待机
#      A720(2-6)  cap=1792 dpc=238  能效比 7.5   中负载主力
#      X4  (7)    cap=1894 dpc=588  能效比 3.2   同频算力仅比A720高5.7%，
#                                        功耗系数却是2.5倍 → 能效黑洞，应拉低
#    → 小核锁 1.1GHz 左右（待机够用）
#    → 5-6 锁 0.96GHz（防升频拉高 X4 电压，同时承接轻负载）
#    → 2-4 锁 1.9GHz 左右（日常主力，避开高频电压暴涨区）
#    → 7 锁 1.9GHz 左右（低于 2.8GHz 电压拐点，避开高频飞天区；
#       同时 CPU 高频会联动拉高 DDR/L3 频率，锁 1.9GHz 时 DDR 仅 2.7GHz，
#       跑到 2.76GHz+ 则 DDR 会跳到 3.7GHz，整机功耗明显上升）
#    → GPU 锁 578MHz（SVS 电压档；实测 dtb 电压表：770MHz 之上每跨一档
#       电压大跳一级，903MHz 比 770MHz 高两级电压、功耗暴涨 54%，
#       578MHz 是日常渲染/视频的能效甜点）
#    追求的是「最佳能效点」而非极限性能，玩游戏若觉得不够可自行调高。
#
#  CPU 频率档位参考 (kHz，实测自本机，不同机型可能略有差异)
#  脚本会自动对齐到「≤目标值」的最近合法档位，填任意值即可生效
#
#  policy0 小核 A520 (cpu0-1)：
#    364800 460800 556800 672000 787200 902400 1017600 1132800 1248000
#    1344000 1459200 1574400 1689600 1804800 1920000 2035200 2150400 2265600
#
#  policy2 中核 A720 高频版 (cpu2-4)：
#    499200 614400 729600 844800 960000 1075200 1190400 1286400 1401600
#    1497600 1612800 1708800 1824000 1920000 2035200 2131200 2188800 2246400
#    2323200 2380800 2438400 2515200 2572800 2630400 2707200 2764800 2841600
#    2899200 2956800 3014400 3072000 3148800
#
#  policy5 中核 A720 低频版 (cpu5-6)：
#    499200 614400 729600 844800 960000 1075200 1190400 1286400 1401600
#    1497600 1612800 1708800 1824000 1920000 2035200 2131200 2188800 2246400
#    2323200 2380800 2438400 2515200 2572800 2630400 2707200 2764800 2841600
#    2899200 2956800
#
#  policy7 大核 X4 (cpu7)：
#    480000 576000 672000 787200 902400 1017600 1132800 1248000 1363200
#    1478400 1593600 1708800 1824000 1939200 2035200 2112000 2169600 2246400
#    2304000 2380800 2438400 2496000 2553600 2630400 2688000 2745600 2803200
#    2880000 2937600 2995200 3052800
#
#  GPU Adreno 750 档位表 (Hz，实测自本机 dtb，不同机型可能略有差异)：
#    频率(MHz)   电压档位         说明
#     903      TURBO_L1(384)    ← 超频档，比770高2个电压大档，能效差
#     834      TURBO   (320)
#     770      NOM_L2  (256)    ← 标称峰值，高频甜点
#     720      NOM     (224)
#     680      SVS_L2  (192)
#     629      SVS_L0  (144)
#     578      SVS     (128)    ← 日常能效（8G3 默认）
#     500      LOW_SVS_L1(80)
#     422      LOW_SVS (64)
#     366      LOW_SVS_D1(60)
#     310      MIN_SVS (56)
#     231      最低档  (52)
