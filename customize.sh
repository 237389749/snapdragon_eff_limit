        sed -i 's/^GPU_FREQ=.*/GPU_FREQ=578000000/' "$FREQ_FILE" 2>/dev/null
    fi
    ui_print "✅ 已生成频率配置文件 config/freq.conf（含双平台完整档位表）"
fi

